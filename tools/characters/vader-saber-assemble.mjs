import fs from 'node:fs';
import path from 'node:path';
import { Matrix4, Vector3, Quaternion } from '../../web/node_modules/three/build/three.module.js';

// Builds web/public/assets/characters/vader-saber.glb from the textured source hilt GLB.
// Node frame = GameplayBones_WeaponBone (Wep_Root) space; all transforms are copied from
// exports/characters/vader-saber/saber-evidence.json (source EBX). The GPU blade template
// mesh is NOT placed here: it is expanded by an unrecovered emitter-graph vertex shader.
// Usage: node tools/characters/vader-saber-assemble.mjs [hilt.glb] [evidence.json] [output.glb]
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../..');
const [hiltFile = path.join(root, 'exports/characters/vader-saber/vader-saber-hilt.glb'),
  evidenceFile = path.join(root, 'exports/characters/vader-saber/saber-evidence.json'),
  output = path.join(root, 'web/public/assets/characters/vader-saber.glb')] = process.argv.slice(2);
const b = fs.readFileSync(hiltFile), len = b.readUInt32LE(12), doc = JSON.parse(b.subarray(20, 20 + len));
const bin = b.subarray(28 + len, 28 + len + b.readUInt32LE(20 + len));
const ev = JSON.parse(fs.readFileSync(evidenceFile, 'utf8'));
if (doc.nodes.length !== 1 || doc.meshes.length !== 1) throw new Error('Expected one converted hilt mesh node');

function frame(t) {
  const m = new Matrix4().fromArray([...t.right, 0, ...t.up, 0, ...t.forward, 0, ...t.trans, 1]);
  const p = new Vector3(), q = new Quaternion(), s = new Vector3(); m.decompose(p, q, s);
  const r = v => Math.abs(v) < 1e-6 ? 0 : Number(v.toFixed(7));
  return { translation: p.toArray().map(r), rotation: q.normalize().toArray().map(r), sourceAxisScale: s.toArray() };
}
const blade = frame(ev.blade.emitterTransformInHiltSpace), light = frame(ev.blade.tubeLight.effectTransformInHiltSpace);
const a = ev.attachment, lm = ev.blade.lengthModel;
doc.nodes = [
  { name: 'vader-saber', children: [1, 2, 3], extras: {
    attach: { gameplayBone: a.gameplayBone, bone: a.skeletonBoneName, sourceBoneIndex: a.skeletonBoneIndex, boneParent: a.skeletonBoneParent,
      localTranslation: a.offset.translation, localRotation: a.offset.rotation, basis: a.offset.basis, mappingBasis: a.mappingBasis },
    note: 'Parent this root to the actor bone named attach.bone with an identity local transform. In the unanimated bind pose Wep_Root is at the model origin, not in the hand; source animations place it.' } },
  { name: 'hilt', mesh: 0, extras: { source: ev.hilt.mesh, renderedBy: ev.hilt.renderedBy, emitter: ev.hilt.emitter } },
  { name: 'blade', translation: blade.translation, rotation: blade.rotation, extras: {
    kind: 'socket (no geometry)', effect: ev.blade.effect, emitterGraph: ev.blade.emitterGraph, templateMesh: ev.blade.templateMesh,
    direction: 'node local +Z (emitter forward) = hilt +Y', bladeLengthOn: lm.bladeLengthOn, bladeLengthSemantics: 'normalised extension (EmitterParameter2)',
    metricLength: null, metricLengthLimitation: lm.metricLengthLimitation, igniteSeconds: lm.igniteSeconds, retractSeconds: lm.retractSeconds,
    colorHdr: ev.blade.colorHdr, colorHdrParameter: 'LightSaberColor1',
    emitterGraphParams: ev.blade.emitterGraphParams.map(p => ({ id: p.propertyId, name: p.name, value: p.vaderValue ?? p.genericDefault, fromGenericDefault: p.vaderValue == null, active: p.inPropertyIdLookupTable })),
    sourceAxisScale: blade.sourceAxisScale } },
  { name: 'blade_light', translation: light.translation, rotation: light.rotation, extras: {
    kind: 'source PbrTubeLight placement (no geometry)', tubeAxis: 'node local +X (light right) = hilt +Y', ...ev.blade.tubeLight, sourceAxisScale: light.sourceAxisScale } },
];
doc.scenes = [{ nodes: [0] }]; doc.scene = 0;
doc.asset = { version: '2.0', generator: 'BF2 source character assembler (vader-saber-assemble.mjs)' };
doc.extras = { ...doc.extras, evidence: ev.evidenceId, sources: ev.sources.map(s => ({ name: s.name, guid: s.guid, sha1: s.sha1 })),
  limitations: ['Blade geometry is GPU-generated by EG_LightSaber_Generic from fx/meshes/weapon/meshp_lightsaber_planes_mesh; the vertex-shader fragment is not recovered, so no blade mesh is included.',
    'Hilt material: exact shader-section texture binding (CS base colour, NAM normal RG); packed NAM AO/mask channels and native shader not reproduced.'] };
const pad = (4 - bin.length % 4) % 4, body = Buffer.concat([bin, Buffer.alloc(pad)]);
doc.buffers[0].byteLength = body.length;
const raw = Buffer.from(JSON.stringify(doc)), json = Buffer.alloc((raw.length + 3) & ~3, 32); raw.copy(json);
const header = Buffer.alloc(20); header.writeUInt32LE(0x46546c67); header.writeUInt32LE(2, 4); header.writeUInt32LE(28 + json.length + body.length, 8); header.writeUInt32LE(json.length, 12); header.writeUInt32LE(0x4e4f534a, 16);
const bh = Buffer.alloc(8); bh.writeUInt32LE(body.length); bh.writeUInt32LE(0x004e4942, 4);
fs.writeFileSync(output, Buffer.concat([header, json, bh, body]));
console.log(JSON.stringify({ output, blade, light, attach: a.skeletonBoneName }));
